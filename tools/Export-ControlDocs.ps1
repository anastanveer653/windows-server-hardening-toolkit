#Requires -Version 5.1
<#
.SYNOPSIS
    Generates docs/CONTROLS.md from the control catalog.

.PARAMETER OutputPath
    Markdown file to write.

.EXAMPLE
    .\tools\Export-ControlDocs.ps1 -OutputPath .\docs\CONTROLS.md
#>
[Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSAvoidUsingWriteHost', '', Justification = 'Developer tool with console output.')]
[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [string]$OutputPath
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$module = Import-Module -Name (Join-Path -Path $PSScriptRoot -ChildPath '..\src\WindowsServerHardening\WindowsServerHardening.psd1') -Force -PassThru
$controls = @(Get-HardeningControl)

function ConvertTo-MarkdownCell {
    param([AllowNull()][string]$Text)
    if (-not $Text) { return '' }
    return ($Text -replace '\|', '\|' -replace '\r?\n', ' ')
}

$categoryOrder = @($controls | ForEach-Object { $_.Category } | Select-Object -Unique)
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Control reference')
$lines.Add('')
$lines.Add("<!-- Generated by tools/Export-ControlDocs.ps1 from the catalog in src/WindowsServerHardening/Controls. Do not edit by hand. -->")
$lines.Add('')
$lines.Add("Windows Server Hardening Toolkit v$($module.Version) ships **$($controls.Count) controls** in $($categoryOrder.Count) categories.")
$lines.Add('')
$lines.Add('Legend: **Opt-in** controls run only when a profile lists them in `EnableControls` (or when selected with `-ControlId`). **Audit-only** controls are evaluated but never changed automatically. **Restart** marks settings that take effect after a reboot. **From** marks controls that are reported as not applicable on older Windows Server releases where the feature does not exist.')
$lines.Add('')
$lines.Add('Benchmark references quote the CIS recommendation title rather than its number, because numbering changes between benchmark versions. Always validate against the benchmark version your organisation has adopted.')
$lines.Add('')
$lines.Add('| Category | Controls | Critical | High | Medium | Low |')
$lines.Add('|---|---:|---:|---:|---:|---:|')
foreach ($category in $categoryOrder) {
    $items = @($controls | Where-Object { $_.Category -eq $category })
    $counts = foreach ($severity in @('Critical', 'High', 'Medium', 'Low')) { @($items | Where-Object { $_.Severity -eq $severity }).Count }
    $lines.Add(('| [{0}](#{1}) | {2} | {3} | {4} | {5} | {6} |' -f $category, $category.ToLowerInvariant(), $items.Count, $counts[0], $counts[1], $counts[2], $counts[3]))
}

foreach ($category in $categoryOrder) {
    $lines.Add('')
    $lines.Add("## $category")
    $lines.Add('')
    $lines.Add('| ID | Severity | Control | Expected | Method | ATT&CK | Notes |')
    $lines.Add('|---|---|---|---|---|---|---|')
    foreach ($control in @($controls | Where-Object { $_.Category -eq $category })) {
        $notes = @()
        if ($control.OptIn) { $notes += 'Opt-in' }
        if ($control.AuditOnly) { $notes += 'Audit-only' }
        if ($control.RebootRequired) { $notes += 'Restart' }
        if (@($control.Roles).Count) { $notes += "Only: $($control.Roles -join ', ')" }
        if (@($control.ExcludeRoles).Count) { $notes += "Not on: $($control.ExcludeRoles -join ', ')" }
        if ($control.MinimumBuild -gt 0) {
            $minimumBuild = $control.MinimumBuild
            $notes += 'From: ' + (& $module { param($Build) Get-HardeningOSRelease -Build $Build } $minimumBuild)
        }
        if ($control.Parameter) { $notes += "Parameter ``$($control.Parameter)``" }

        $method = switch ($control.Type) {
            'Registry'        { 'Registry: `{0}\{1}`' -f $control.Target.Path, $control.Target.Name }
            'Service'         { 'Service: `{0}`' -f $control.Target.Name }
            'SmbServer'       { 'SMB server: `{0}`' -f $control.Target.Property }
            'FirewallProfile' { 'Firewall profile: `{0}`' -f $control.Target.Property }
            'FirewallRule'    { 'Firewall rule: `{0}`' -f $control.Target.Name }
            'AuditPolicy'     { 'Audit policy: {0}' -f $control.Target.Subcategory }
            'SecurityPolicy'  { 'Security policy: `{0}`' -f $control.Target.Key }
            default           { 'Check: {0}' -f $control.Target.Check }
        }
        $attack = (@($control.MitreAttack) | ForEach-Object { '[{0}](https://attack.mitre.org/techniques/{1}/)' -f $_, ($_ -replace '\.', '/') }) -join ' '

        $lines.Add(('| {0} | {1} | {2} | {3} | {4} | {5} | {6} |' -f $control.Id, $control.Severity,
                (ConvertTo-MarkdownCell $control.Title), (ConvertTo-MarkdownCell $control.ExpectedDisplay),
                (ConvertTo-MarkdownCell $method), $attack, ($notes -join ', ')))
    }

    $lines.Add('')
    $lines.Add('<details><summary>Rationale and impact</summary>')
    $lines.Add('')
    foreach ($control in @($controls | Where-Object { $_.Category -eq $category })) {
        $entry = "- **$($control.Id) $(ConvertTo-MarkdownCell $control.Title)**: $(ConvertTo-MarkdownCell $control.Rationale)"
        if ($control.Impact) { $entry += " *Impact:* $(ConvertTo-MarkdownCell $control.Impact)" }
        $entry += " *Benchmark:* $(ConvertTo-MarkdownCell $control.Benchmark)."
        $lines.Add($entry)
    }
    $lines.Add('')
    $lines.Add('</details>')
}

$directory = Split-Path -Path ([System.IO.Path]::GetFullPath($OutputPath)) -Parent
[void][System.IO.Directory]::CreateDirectory($directory)
[System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($OutputPath), (($lines -join "`n") + "`n"), [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $($controls.Count) controls to $OutputPath"
